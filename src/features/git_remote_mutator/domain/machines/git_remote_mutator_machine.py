from typing import Dict, Set

STATE_IDLE = "IDLE"
STATE_VERIFYING_REF = "VERIFYING_REF"
STATE_CREATING_BLOBS = "CREATING_BLOBS"
STATE_CREATING_TREE = "CREATING_TREE"
STATE_CREATING_COMMIT = "CREATING_COMMIT"
STATE_UPDATING_REF = "UPDATING_REF"
STATE_UPDATING_GRAPH = "UPDATING_GRAPH"
STATE_COMPLETED = "COMPLETED"
STATE_FAILED = "FAILED"

_VALID_TRANSITIONS: Dict[str, Set[str]] = {
    STATE_IDLE: {STATE_VERIFYING_REF, STATE_FAILED},
    STATE_VERIFYING_REF: {STATE_CREATING_BLOBS, STATE_FAILED},
    STATE_CREATING_BLOBS: {STATE_CREATING_TREE, STATE_FAILED},
    STATE_CREATING_TREE: {STATE_CREATING_COMMIT, STATE_FAILED},
    STATE_CREATING_COMMIT: {STATE_UPDATING_REF, STATE_FAILED},
    STATE_UPDATING_REF: {STATE_UPDATING_GRAPH, STATE_FAILED},
    STATE_UPDATING_GRAPH: {STATE_COMPLETED, STATE_FAILED},
    STATE_COMPLETED: set(),
    STATE_FAILED: set(),
}


def transition_to(current_state: str, next_state: str) -> str:
    valid_targets = _VALID_TRANSITIONS.get(current_state, set())
    if next_state not in valid_targets:
        raise ValueError(f"Invalid state transition from {current_state} to {next_state}")
    return next_state
